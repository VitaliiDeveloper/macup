#!/bin/bash
# Builds the macup binary. Its translations live in src/i18n/translations.json ({"English": {"uk": …, "ru": …}}) and are
# embedded as Sources/macup/Generated/Translations.swift, which is not committed.
#   ./build.sh --check   fails if Translations.swift or macup.sha256 is out of date, or the package does not build
# The root macup is no build output: it is the bootstrap that moves a 2.9 install onto the binary (2.9's self-update reads
# it from main), committed together with its macup.sha256.
set -eo pipefail
cd "$(dirname "$0")"

GEN=Sources/macup/Generated
gen=$(mktemp -d "${TMPDIR:-/tmp}/macup-gen.XXXXXX"); trap 'rm -rf "$gen"' EXIT
python3 - src/i18n/translations.json "$gen" <<'PY'
import json, re, sys
def literal(text):   # a raw multi-line literal whose value is exactly the text
    hashes = 1   # enough #s that neither the closing delimiter nor an escape occurs in the text
    while '"""' + '#' * hashes in text or '\\' + '#' * hashes in text:
        hashes += 1
    fence = '#' * hashes
    return f'{fence}"""\n{text}\n"""{fence}'
path, out = sys.argv[1:3]
text = open(path, encoding="utf-8").read()
if "\r" in text:
    sys.exit(f"build.sh: {path} has a carriage return, which a Swift literal would not keep")
bad = False
for en, translations in json.loads(text).items():
    for lang in ("uk", "ru"):
        translation = translations.get(lang)
        if not translation:
            print(f"build.sh: no {lang} translation for {en!r}", file=sys.stderr); bad = True
        elif re.findall(r"%[sd%]", en) != re.findall(r"%[sd%]", translation):
            print(f"build.sh: {lang} placeholders differ for {en!r}", file=sys.stderr); bad = True
if bad:
    sys.exit(1)
with open(f"{out}/Translations.swift", "w", encoding="utf-8") as handle:
    handle.write(f"// Generated by build.sh from {path}. Do not edit.\nenum Translations {{\n    static let json = {literal(text)}\n}}\n")
PY

if [ "${1:-}" = --check ]; then
  # 2.9's self-update installs main/macup only when it matches main/macup.sha256
  [ "$(cat macup.sha256 2>/dev/null)" = "$(shasum -a 256 macup | awk '{print $1}')  macup" ] \
    || { echo "macup.sha256 does not match macup: write it with  echo \"\$(shasum -a 256 macup | awk '{print \$1}')  macup\" >macup.sha256" >&2; exit 1; }
  for file in "$gen"/*.swift; do cmp -s "$file" "$GEN/${file##*/}" || { echo "$GEN/${file##*/} is out of date: run ./build.sh" >&2; exit 1; }; done
  swift build -q || { echo "the Swift package does not build" >&2; exit 1; }
  echo "macup is up to date"
else
  mkdir -p "$GEN"; rm -f "$GEN/LegacyScript.swift"   # an older checkout's copy of the bash build: the binary carries no bash
  for file in "$gen"/*.swift; do cmp -s "$file" "$GEN/${file##*/}" || cp "$file" "$GEN/${file##*/}"; done   # unchanged files keep their date: no rebuild
  swift build -q && echo "built $(swift build --show-bin-path)/macup"
fi
