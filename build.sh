#!/bin/bash
# Builds the single-file bash `macup` from src/, then the Swift binary, which carries that script. Edit src/, then run ./build.sh.
#   ./build.sh --check   fails if a built file is out of date (macup, macup.sha256, Sources/macup/Generated) or the package does not build
#   MACUP_NO_SWIFT=1     only the bash script (CI's lint job, on Linux)
# None of the built files is committed on swift/main: CI builds them.
# Translations live in src/i18n/translations.json ({"English": {"uk": …, "ru": …}}) and are
# embedded at build time, so macup itself needs no JSON parser.
# `@py file` embeds a Python file as $MACUP_PY: python3 stays optional and macup stays one file.
set -eo pipefail
cd "$(dirname "$0")"

# bash runs the script top to bottom, so the order matters
ORDER="core help commands translations arguments checks updates tools cleanup leftovers cleaners report summary"
for file in src/*.sh; do
  case " $ORDER " in *" $(basename "$file" .sh) "*) ;; *) echo "build.sh: add $file to ORDER" >&2; exit 1 ;; esac
done

i18n(){ # language → "English || translation" lines; fails if any entry lacks the language or a placeholder
  python3 - "$1" src/i18n/translations.json <<'PY'
import json, re, sys
lang, path = sys.argv[1], sys.argv[2]
bad = 0
for en, tr in json.load(open(path, encoding="utf-8")).items():
    translation = tr.get(lang)
    if not translation:
        print(f"build.sh: no {lang} translation for {en!r}", file=sys.stderr); bad = 1; continue
    if re.findall(r"%[sd%]", en) != re.findall(r"%[sd%]", translation):
        print(f"build.sh: {lang} placeholders differ for {en!r}", file=sys.stderr); bad = 1
    if "\n" in en + translation or " || " in en + translation:
        print(f"build.sh: newline or ' || ' in {en!r}", file=sys.stderr); bad = 1
    print(f"{en} || {translation}")
sys.exit(bad)
PY
}

PY_END=MACUP_PY_END
py(){ # Python file → a bash statement that sets MACUP_PY to its text
  python3 -c 'import ast, sys; ast.parse(open(sys.argv[1], encoding="utf-8").read(), sys.argv[1], feature_version=(3, 9))' "$1" || { echo "build.sh: $1 does not compile" >&2; return 1; }
  ! grep -qx "$PY_END" "$1" || { echo "build.sh: $1 has a line $PY_END" >&2; return 1; }
  printf "IFS= read -r -d '' MACUP_PY <<'%s' || :\n" "$PY_END"; awk 1 "$1"; printf '%s\n' "$PY_END"
}

tmp=$(mktemp "${TMPDIR:-/tmp}/macup-build.XXXXXX"); trap 'rm -f "$tmp"' EXIT
for name in $ORDER; do
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in "@i18n "*) i18n "${line#@i18n }" ;; "@py "*) py "${line#@py }" ;; *) printf '%s\n' "$line" ;; esac
  done <"src/$name.sh"
done >"$tmp"
/bin/bash -n "$tmp"

# self-update and the installer compare the download with this before they install it
sum256(){ if command -v shasum >/dev/null 2>&1; then shasum -a 256 "$1"; else sha256sum "$1"; fi | awk '{print $1}'; }
SUM="$(sum256 "$tmp")  macup"

# the Swift binary carries the bash build (it runs whatever is not ported yet) and the translations, as raw string literals
GEN=Sources/macup/Generated
gen=$(mktemp -d "${TMPDIR:-/tmp}/macup-gen.XXXXXX"); trap 'rm -f "$tmp"; rm -rf "$gen"' EXIT
python3 - "$tmp" src/i18n/translations.json "$gen" <<'PY'
import sys
def literal(text):   # a raw multi-line literal whose value is exactly the text
    hashes = 1   # enough #s that neither the closing delimiter nor an escape occurs in the text
    while '"""' + '#' * hashes in text or '\\' + '#' * hashes in text:
        hashes += 1
    fence = '#' * hashes
    return f'{fence}"""\n{text}\n"""{fence}'
script, translations, out = sys.argv[1:4]
for name, typ, prop, path in (("LegacyScript", "the bash build", "text", script), ("Translations", "src/i18n/translations.json", "json", translations)):
    text = open(path, encoding="utf-8").read()
    if "\r" in text:
        sys.exit(f"build.sh: {path} has a carriage return, which a Swift literal would not keep")
    with open(f"{out}/{name}.swift", "w", encoding="utf-8") as handle:
        handle.write(f"// Generated by build.sh from {typ}. Do not edit.\nenum {name} {{\n    static let {prop} = {literal(text)}\n}}\n")
PY

if [ "${1:-}" = --check ]; then
  cmp -s "$tmp" macup || { echo "macup is out of date: run ./build.sh" >&2; exit 1; }
  [ "$(cat macup.sha256 2>/dev/null)" = "$SUM" ] || { echo "macup.sha256 is out of date: run ./build.sh" >&2; exit 1; }
  if [ -z "${MACUP_NO_SWIFT:-}" ]; then
    for file in "$gen"/*.swift; do cmp -s "$file" "$GEN/${file##*/}" || { echo "$GEN/${file##*/} is out of date: run ./build.sh" >&2; exit 1; }; done
    swift build -q || { echo "the Swift package does not build" >&2; exit 1; }
  fi
  echo "macup is up to date"
else
  cp "$tmp" macup; chmod 755 macup; echo "$SUM" >macup.sha256; echo "built macup ($(wc -l <macup | tr -d ' ') lines)"
  [ -n "${MACUP_NO_SWIFT:-}" ] && exit 0
  mkdir -p "$GEN"
  for file in "$gen"/*.swift; do cmp -s "$file" "$GEN/${file##*/}" || cp "$file" "$GEN/${file##*/}"; done   # unchanged files keep their date: no rebuild
  swift build -q && echo "built $(swift build --show-bin-path)/macup"
fi
